### Контекст: стагнация, а не кризис

Самая сложная управленческая ситуация — не кризис. Кризис понятен: срываются сроки, падают метрики, конфликты выходят наружу.

Гораздо сложнее другое состояние: проект идёт, команда работает, катастрофы нет — но за последний период сменились люди, задачи наслаивались, фокус размывался. Появляется ощущение стагнации. Именно в этот момент нужно планировать следующий год.

Вопросы без ответов: кому давать новые проекты? Кто хочет углубляться в текущее? Кто внутренне «дорабатывает» и просто не говорит об этом? Без этого стратегическое планирование превращается в игру в угадайку.

