### Что сделали

Инструмент — **Moving Motivators** из Management 3.0. Подход намеренно простой: без внешних консультантов, длинной подготовки и сложных методологий.

Каждый участник команды:

1. Ранжировал мотивационные драйверы (мастерство, цель, взаимосвязь, свобода, статус, безопасность и др.) по степени личной важности
2. Оценивал, насколько каждый из них реализован в текущей работе

После этого — индивидуальная встреча (~1 час), на которой обсуждали разрывы между «важно» и «реализовано», уточняли ожидания, фиксировали конкретные действия.

**Итог подготовки:** меньше часа. Всего — 7 встреч.

---

### Что вскрылось в процессе

**1. Встречи оказались значительно глубже обычных 1:1.**
Инструмент создал безопасную рамку для обсуждения того, что редко поднимается напрямую: неудовлетворённость, сомнения, внутренние ожидания.

**2. Системная зона: низко реализован драйвер «взаимосвязь».**
У нескольких сотрудников — слабая коммуникация с другими отделами, неясность зон ответственности. Это организационный сигнал, а не индивидуальная проблема.

**3. Приоритеты команды оказались зрелыми.**
В топе у большинства — мастерство, цель и взаимосвязь. Фокус на развитии и смысле, а не только на внешних стимулах.

**4. Один сотрудник «внутренне вышел из роли».**
Его ключевой мотиватор находился вне того, что компания могла предложить. Через месяц он ушёл — спокойно, без конфликта и с пониманием причин с обеих сторон.

---

### Результаты

- Большинство договорённостей, зафиксированных на встречах, выполнены или находятся в работе
- Планирование следующего года опиралось на проговорённые ожидания, а не на предположения
- Распределение задач стало более осознанным с точки зрения драйверов сотрудников
- Уход сотрудника прошёл без управленческого кризиса и эмоционального напряжения

Нельзя утверждать, что рост вовлечённости — исключительно следствие этого инструмента. Но можно точно сказать: качество управленческих решений стало выше за счёт большей прозрачности.

---

### Ограничения

Формат оптимален для небольшой команды — **до 8–10 человек**. Каждая встреча требует ~1 часа глубокой концентрации и эмоциональной вовлечённости, плюс трекинг договорённостей.

В команде 20+ человек инструмент эффективнее использовать точечно: с ключевыми ролями, в период изменений, при признаках падения вовлечённости.

