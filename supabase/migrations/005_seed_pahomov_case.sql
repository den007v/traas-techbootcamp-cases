### Что можно повторить у себя

Необязательно собирать HomeLab на 28 контейнеров, чтобы получить 80% эффекта.

**Вариант «на своём железе»:** Mac mini или Mac Studio с 64 ГБ совместной памяти → в шкаф с резервированием питания → внешние диски → Docker + Whisper для распознавания речи + LLM для саммари.

**Вариант «через подписки»:** Не собирать ничего, а использовать готовые сервисы для записи, транскрибации и саммаризации встреч. Менее гибко, формат под себя не настроишь так точно — но рабочий вариант без порога входа.

Сам принцип — «записать → распознать → структурировать → положить в единую базу» — можно реализовать на разном уровне сложности. Начать с простого, а дальше достраивать по мере необходимости.

