### С чего всё началось

После переезда в новую квартиру начался стандартный процесс: подбор роутера, бесперебойника, сетевых свитчей. Всё новое — кроме одного устройства. NAS (Network Attached Storage — сетевое хранилище, по сути коробка с жёсткими дисками, к которой обращаются все устройства в домашней сети) в списке на замену не значился. Он же работает, зачем трогать.

На этом NAS хранилось около 6 терабайт данных: торрент-качалка, обширная медиатека (фильмы, сериалы — всё через сетевую папку), видеозаписи с умного дверного звонка и сетевая файлопомойка.

**День Х**

В какой-то момент NAS просто перестал записывать данные. Это был шанс — удалось спасти часть файлов почти с первой попытки. Дальше — перезагрузка. И тишина: RAID0 (способ объединения дисков ради скорости, но без какой-либо страховки — если один диск умирает, все данные теряются целиком) превратился в «труп».

При этом катастрофы не произошло: 99% того, что хранилось на NAS, можно было скачать заново, а оставшийся 1% либо не был критичен, либо был продублирован в облаке. Рабочие файлы уцелели полностью. Но исчезла сама инфраструктура — медиасервер, качалка, архив записей с камеры, файлообменник. Восстанавливать всё это по частям не хотелось.

**Первая мысль — «Куплю новые диски и всё»**

Именно так звучал изначальный план. Заменить диски, поднять всё заново и забыть. Но стоило начать изучать, что сейчас есть на рынке, как стало понятно: современные NAS умеют гораздо больше, чем просто хранить файлы.

Требования при этом оставались простыми:

- Минимум два жёстких диска (HDD)
- Поддержка SSD (быстрых твердотельных накопителей)
- Потребление не больше 40 Вт — бесперебойник в шкафу уже стоял
- Процессор, способный конвертировать видео для трансляции по сети
- Удобное ПО и магазин приложений (на старте это было важно — Docker ещё не был опробован на практике)

Задачи тоже пока были обычные: вернуть медиасервер, качалку, файлопомойку и настроить доступ ко всему этому с телефона из любой точки мира.

**Новогодний инсайт: «а что, если оно будет САМО?»**

Новогодние праздники и YouTube — комбинация, способная завести далеко. В какой-то момент в ленте появился ролик про Arr-стек — набор приложений, которые полностью автоматизируют поиск, скачивание и раскладку фильмов и сериалов по нужным папкам.

«А когда оно САМО, тогда оно мне точно нужно».

Под рукой оказался ИИ-ассистент (Perplexity), который генерировал docker-compose файлы и помогал с настройкой. Поставили Docker, накинули Portainer, стали закидывать compose-файлы на сервер с молитвой «лишь бы запустилось».

Самой большой проблемой оказалась отладка. Помимо семи основных приложений каждое из них нужно было корректно подружить с VPN-прокси — без этого никуда. Два дня ушло на то, чтобы всё заработало вместе. И после этого пришло осознание: «Я и сам чет могу».

YouTube-лента окончательно превратилась в поток Homelab-контента. Начали появляться новые идеи — что ещё можно поднять на домашнем сервере.

