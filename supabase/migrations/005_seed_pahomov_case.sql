- На старте — Perplexity. Писал docker-compose файлы, помогал собирать конфиги, решал проблемы при настройке.
- После перехода на собственные инструменты — OpenWebUI + SearXNG + Ollama. Локальная модель (ministral-3b:14b) для большинства задач, облачная Kimi k2.5 через Ollama — когда локальной мощности не хватало.
