### Проблема, которую никто не планировал решать

HomeLab изначально собирался ради медиа и умного дома. Но параллельно существовала другая боль — совершенно не связанная с домашним сервером.

Руководитель с плотным графиком встреч постоянно сталкивается с одним и тем же: конспекты созвонов либо не делаются вообще, либо делаются кое-как и теряются. Договорённости забываются, контекст размывается, приходится переспрашивать или восстанавливать по памяти. «Я часто забывал это делать» — проблема не в нехватке инструментов, а в том, что ручная фиксация требует дисциплины, которая в потоке управленческих задач неизбежно проседает.

В какой-то момент стало понятно: дома уже стоит сервер с языковыми моделями, сервис распознавания речи и конструктор автоматизаций. Все кубики есть — осталось собрать из них конвейер, который будет делать конспекты автоматически.

**Пайплайн «встреча → заметка → Telegram»**

Сейчас 100% встреч проходят через этот конвейер. Ручные записи параллельно со встречей больше не ведутся. Вот как это работает, шаг за шагом:

1. **Запись звука.** Звук звонка и микрофона объединяются в один поток через WaveLink. Этот поток записывается в .wav-файл через Recordia. Главное — не забыть нажать кнопку записи.

2. **Доставка на сервер.** Как только файл сохранён, Syncthing автоматически подхватывает его и синхронизирует на NAS. Неважно, где находишься: если нет доступа к локальной сети, включается Tailscale.

3. **Запуск автоматизации.** На NAS работает n8n, и первым триггером в сценарии стоит «появился новый файл в папке». Как только файл прилетает — цепочка стартует.

4. **Распознавание речи.** n8n отправляет .wav-файл на Linux-машину в WhisperX (модель Large, русский язык). WhisperX превращает аудио в текст с таймкодами и разделением по спикерам, возвращает результат в формате JSON.

5. **Очистка текста.** Пара JavaScript-нод в n8n вычищает из текста мусор и технические данные — чтобы не тратить лишние токены на следующем шаге.

6. **Генерация саммари.** Подготовленный текст уходит в языковую модель через Ollama. Модель по заранее продуманному промпту (это примерно 20-я итерация) формирует структурированную заметку в Markdown: краткое описание встречи, список принятых решений, список действий с ответственными и дедлайнами.

7. **Доставка результата.** Готовая заметка одновременно сохраняется в хранилище Obsidian на NAS и отправляется в Telegram-бот. Syncthing синхронизирует хранилище на все устройства — заметка появляется везде.

**Скорость**

- 30-минутная встреча → готовая заметка за 2–3 минуты
- Часовая встреча → 5–7 минут
- Очень длинные встречи (2+ часа) — WhisperX пока ругается на размер файла. Таких встреч мало, починка в планах.

