### Как родился HomeLab: от нового NAS до набора сервисов

**Железо**

Выбор остановился на готовом устройстве с возможностью доработки — Asustor Numbustor2 Gen2. К нему были докуплены:

- 2 × SSD по 1 ТБ (WD RED) — объединены в RAID1 (зеркалирование). Здесь крутятся все контейнеры и база данных фотохранилища.
- 2 × HDD по 8 ТБ (Seagate) — объединены в RAID0 (скорость без резервирования). Здесь живёт медиатека, файлопомойка и записи с камер. Подход осознанный: если развалится — данные можно перекачать.
- Оперативная память — увеличена до 16 ГБ.
- Процессор — Intel N5105, встроен в NAS, отлично справляется с основными задачами.

NAS тихо стоит в шкафу и потребляет свои скромные ватты. Для задач, требующих серьёзной вычислительной мощности — прежде всего для работы ИИ-моделей — используется отдельная машина: игровой ПК с Ubuntu (i5-13600K, RTX 4070 с 12 ГБ видеопамяти, 32 ГБ оперативной памяти). Именно эта машина даёт ту видеопамять, которой NAS не хватает для нейросетей.

**Что на всём этом крутится**

Сейчас на двух машинах живёт 28 контейнеров. Основные группы:

*Медиа-автоматизация (Arr-стек):* Jellyfin, Jellyseerr, qBittorrent, Sonarr, Radarr, Prowlarr, Huntarr

*Умный дом:* Home Assistant

*Фото и файлы:* Immich (замена облачным фотосервисам с ИИ-поиском), NextExplorer

*ИИ-инструменты:* OpenWebUI, Ollama, SearXNG

*Автоматизации:* n8n — визуальный конструктор сценариев

*Синхронизация и сеть:* Syncthing, AdGuard Home, v2raya, Tailscale

*Мониторинг:* Portainer, Glances, Dozzle, dash., Homarr, Tugtainer

*Распознавание речи:* WhisperX — сервис превращения голоса в текст, работает на Linux-машине с видеокартой

Из всего этого «обязательная база» — медиа-стек, умный дом и контроль домашней сети. Остальное — скорее приятные «игрушки».

