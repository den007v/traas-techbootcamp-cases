### Что изменилось в работе

Главная ценность — не экономия времени (хотя и она есть), а сам факт фиксации. Конспекты теперь появляются по умолчанию, без отдельного усилия.

Как эти заметки используются дальше:

- Отчётные встречи — по ним через LLM запускается поиск, чтобы понять общий прогресс: куда движемся и как быстро.
- Встречи рабочих групп по проектам — заметки распределяются по проектам и помогают обновлять дорожные карты.
- 1-на-1 и командные активности — привязываются к конкретным сотрудникам. Появляется возможность отслеживать динамику людей и выполнение обещаний.

Следующий шаг — связать Obsidian, NotebookLM и Claude Code, чтобы саммари встреч автоматически линковались к проектам и актуализировали в них информацию.

