### Грабли и честные ограничения

- Главная боль — подбор связки «промпт + модель». Цель была сделать весь конвейер полностью локальным, без обращения к облачным сервисам. Не получилось: все протестированные локальные модели размером до 14 млрд параметров не давали стабильного качества саммари. При обширном контексте они не помещались в видеопамять и начинали работать на процессоре, что критично замедляло процесс и ухудшало результат. Для устойчивого качества пока используется облачная модель.
- Цикл отладки был простой, но бесконечный: сделал → получил ошибку → закинул в LLM → исправил → повторил. Опыта в настройке таких систем было мало, поэтому повторений было много.
- Промпт для саммари — примерно 20-я итерация. Когда инструмент свой, настройки делаются под себя именно тогда, когда нужно. В этом и есть основная ценность.

